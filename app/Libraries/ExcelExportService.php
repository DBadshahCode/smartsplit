        }
        $ws->getColumnDimension($this->colLetter($extraDescCol))->setWidth(22);
        $ws->getColumnDimension($this->colLetter($extraAmtCol))->setWidth(18);
        $ws->getColumnDimension($this->colLetter($extraInvCol))->setWidth(22);
