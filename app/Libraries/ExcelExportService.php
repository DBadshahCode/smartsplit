            ]);
        }
        $ws->getRowDimension(1)->setRowHeight(20);

        $row = 2;
        $now = date('Y-m-d H:i:s');
        foreach ($users as $user) {
            $uid = $user['id'];
            $dist = $distributions[$uid] ?? [];
            $ws->setCellValue("A{$row}", $month);
            $ws->setCellValue("B{$row}", $uid);
            $ws->setCellValue("C{$row}", $user['name']);
