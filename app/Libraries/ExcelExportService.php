        foreach (['A', 'B', 'C', 'D', 'E', 'F', 'G', 'H'] as $col) {
            $this->styleCell($ws, "{$col}1", [
                'font' => ['bold' => true, 'color' => self::WHITE],
                'fill' => self::NAVY,
